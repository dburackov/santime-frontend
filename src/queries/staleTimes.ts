// Модуль намеренно без 'use client': константы импортируют и серверные модули.
//
// Нулевой staleTime раньше стоял везде, чтобы рефетч при монтировании подменял
// возможно устаревшую цену из ISR-кэша страницы. Окно ISR — час, поэтому минуты
// кэша на клиенте достаточно, а обычная перезагрузка перестаёт тянуть те же
// ~27 КБ второй раз следом за гидрацией.

/** Подборки товаров: цена может измениться, но не за минуту. */
export const STOREFRONT_STALE_TIME = 60_000;

/** Корзина: цена и наличие могут измениться, итог всё равно сверяется при заказе. */
export const CART_STALE_TIME = 30_000;

/** Справочники: категории и промокоды правятся руками и редко. */
export const REFERENCE_STALE_TIME = 5 * 60_000;
