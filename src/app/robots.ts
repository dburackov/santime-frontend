import type { MetadataRoute } from 'next';
import { SITE_URL } from '@/config/siteInfo';

export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: '*',
      // Пагинация — единственный query-параметр, ведущий на действительно другой
      // контент, поэтому она исключена из общего запрета ниже. Allow должен идти
      // раньше Disallow: при равной длине правил приоритет у первого совпадения.
      //
      // /img/ — не про контент, а про то, что запрет ниже иначе съедает вообще все
      // картинки: ImgproxyUrlBuilder дописывает к каждой ссылке ?v=N под инвалидацию
      // кэша, и она попадает под /*?*. Правило длиннее запрета (5 символов против 4),
      // поэтому по специфичности выигрывает оно. Без этого робот не имеет права
      // скачать ни одного фото, а вместе с ними отваливается и image в JSON-LD
      // товара — Google требует, чтобы картинка оттуда была доступна для обхода.
      allow: ['/', '/*?page=', '/img/'],
      disallow: [
        '/admin',
        '/api/admin',
        '/cart',
        '/checkout',
        '/order-confirmation',
        // Фильтры категории живут в query-string и дают бесконечное число почти
        // одинаковых URL. Серверный noindex для них тоже стоит, но до страницы
        // лучше вовсе не пускать — экономия краулингового бюджета.
        '/*?*',
      ],
    },
    sitemap: `${SITE_URL}/sitemap.xml`,
  };
}
