-- =====================================================================
-- СХЕМА БД ИНТЕРНЕТ-МАГАЗИНА
-- Подход: универсальные поля — обычные колонки,
--         категорийно-специфичные атрибуты — JSONB
-- =====================================================================

-- Расширение для мониторинга запросов (нужно для отслеживания
-- нагрузки на фильтры через pg_stat_statements при необходимости)
-- CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

-- =====================================================================
-- КАТЕГОРИИ И БРЕНДЫ
-- =====================================================================

CREATE TABLE category
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_parent_category BIGINT REFERENCES category (id),

    name               VARCHAR(255) NOT NULL,
    slug               VARCHAR(255) NOT NULL UNIQUE,

    created_at         TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE brand
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name       VARCHAR(255) NOT NULL,
    slug       VARCHAR(255) NOT NULL UNIQUE,

    created_at TIMESTAMP    NOT NULL DEFAULT now()
);

-- =====================================================================
-- АТРИБУТЫ (метаданные — используются для управления через админку
-- и для генерации UI фильтров на фронте, без хардкода категорий)
-- =====================================================================

CREATE TYPE attribute_type AS ENUM ('STRING', 'NUMBER', 'BOOLEAN', 'OPTION');

CREATE TABLE attribute
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(255)   NOT NULL,
    slug VARCHAR(255)   NOT NULL UNIQUE, -- используется как ключ в JSONB
    type attribute_type NOT NULL,
    unit VARCHAR(50)                     -- напр. "GB", "см", "кг" — для отображения на фронте
);

CREATE TABLE attribute_option
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_attribute BIGINT       NOT NULL REFERENCES attribute (id) ON DELETE CASCADE,

    value        VARCHAR(255) NOT NULL,

    UNIQUE (id_attribute, value)
);

-- Связь атрибута с категорией: какие атрибуты доступны в категории,
-- обязательны ли, участвуют ли в фильтрах, различают ли варианты товара
CREATE TABLE category_attribute
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_category  BIGINT  NOT NULL REFERENCES category (id) ON DELETE CASCADE,
    id_attribute BIGINT  NOT NULL REFERENCES attribute (id) ON DELETE CASCADE,

    required     BOOLEAN NOT NULL DEFAULT FALSE,
    is_filter    BOOLEAN NOT NULL DEFAULT FALSE,
    is_variant   BOOLEAN NOT NULL DEFAULT FALSE,

    sort_order   INT     NOT NULL DEFAULT 0, -- порядок отображения фильтров/полей на фронте

    UNIQUE (id_category, id_attribute)
);

-- =====================================================================
-- ТОВАРЫ И ВАРИАНТЫ
-- =====================================================================

CREATE TABLE product
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_category BIGINT       NOT NULL REFERENCES category (id),
    id_brand    BIGINT REFERENCES brand (id),

    name        VARCHAR(255) NOT NULL,
    slug        VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,

    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,

    created_at  TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE product_variant
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_product     BIGINT         NOT NULL REFERENCES product (id) ON DELETE CASCADE,

    slug           VARCHAR(255)   NOT NULL UNIQUE, -- человекочитаемый URL карточки варианта в каталоге
    sku            VARCHAR(255)   NOT NULL UNIQUE,
    price          NUMERIC(12, 2) NOT NULL,
    stock_quantity INT            NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    weight_kg      NUMERIC(8, 3), -- универсальное поле, нужно почти всегда (для доставки)

    -- Категорийно-специфичные атрибуты (RAM, цвет, размер экрана и т.д.)
    -- Ключи в JSON = attribute.slug
    attributes     JSONB          NOT NULL DEFAULT '{}'::jsonb,

    created_at     TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP      NOT NULL DEFAULT now()
);

CREATE TABLE product_image
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_product BIGINT REFERENCES product (id) ON DELETE CASCADE,
    id_variant BIGINT REFERENCES product_variant (id) ON DELETE CASCADE,

    path       VARCHAR(255) NOT NULL,
    sort_order INT          NOT NULL DEFAULT 0,

    CHECK (id_product IS NOT NULL OR id_variant IS NOT NULL)
);

-- =====================================================================
-- ЗАКАЗЫ
-- =====================================================================

CREATE TABLE "order"
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    status          VARCHAR(50)    NOT NULL,

    first_name      VARCHAR(255)   NOT NULL,
    last_name       VARCHAR(255)   NOT NULL,

    email           VARCHAR(255),
    phone           VARCHAR(50),

    address         VARCHAR(500),
    postal_code     VARCHAR(50),
    city            VARCHAR(255),

    payment_method  VARCHAR(50)    NOT NULL,
    delivery_method VARCHAR(50)    NOT NULL,

    comment         TEXT,

    total_price     NUMERIC(12, 2) NOT NULL,

    created_at      TIMESTAMP      NOT NULL DEFAULT now()
);

CREATE TABLE order_item
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_order           BIGINT         NOT NULL REFERENCES "order" (id) ON DELETE CASCADE,
    id_product_variant BIGINT REFERENCES product_variant (id),

    product_name       VARCHAR(255)   NOT NULL, -- снапшот на момент заказа
    sku                VARCHAR(255)   NOT NULL,

    price              NUMERIC(12, 2) NOT NULL,
    quantity           INT            NOT NULL CHECK (quantity > 0)
);

-- =====================================================================
-- ИНДЕКСЫ
-- =====================================================================

-- Базовые связи
CREATE INDEX idx_product_category ON product (id_category);
CREATE INDEX idx_product_brand ON product (id_brand);
CREATE INDEX idx_product_active ON product (is_active) WHERE is_active = TRUE;

CREATE INDEX idx_variant_product ON product_variant (id_product);
CREATE INDEX idx_variant_price ON product_variant (price);
CREATE INDEX idx_variant_stock ON product_variant (stock_quantity) WHERE stock_quantity > 0;

CREATE INDEX idx_image_product ON product_image (id_product);
CREATE INDEX idx_image_variant ON product_image (id_variant);

CREATE INDEX idx_order_item_order ON order_item (id_order);
CREATE INDEX idx_order_item_variant ON order_item (id_product_variant);

CREATE INDEX idx_order_status ON "order" (status);
CREATE INDEX idx_order_created_at ON "order" (created_at);

-- Метатаблицы атрибутов
CREATE INDEX idx_category_attribute_category ON category_attribute (id_category);
CREATE INDEX idx_category_attribute_filter ON category_attribute (id_category) WHERE is_filter = TRUE;
CREATE INDEX idx_attribute_option_attribute ON attribute_option (id_attribute);

-- Универсальный GIN-индекс для точечных/OPTION/BOOLEAN фильтров по JSONB
-- Покрывает запросы вида: attributes @> '{"color": "black"}'
CREATE INDEX idx_variant_attributes_gin ON product_variant USING GIN (attributes);

-- Expression-индексы под конкретные NUMBER-атрибуты (range-фильтры) НЕ создаются
-- здесь заранее — они создаются автоматически приложением через
-- CREATE INDEX CONCURRENTLY IF NOT EXISTS в момент, когда атрибут
-- помечается is_filter = true в category_attribute (см. CategoryAttributeService).
--
-- Пример того, что будет сгенерировано автоматически:
-- CREATE INDEX CONCURRENTLY idx_variant_attr_ram
--     ON product_variant (((attributes->>'ram')::numeric));

-- =====================================================================
-- ТРИГГЕРЫ: автообновление updated_at
-- =====================================================================

CREATE OR REPLACE FUNCTION set_updated_at()
    RETURNS TRIGGER AS
$$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_category_updated_at
    BEFORE UPDATE
    ON category
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_product_updated_at
    BEFORE UPDATE
    ON product
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_variant_updated_at
    BEFORE UPDATE
    ON product_variant
    FOR EACH ROW
EXECUTE FUNCTION set_updated_at();
